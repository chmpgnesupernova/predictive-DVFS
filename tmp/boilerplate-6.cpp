enum FSMState {
    STRONGLY_NOT_TAKEN,
    WEAKLY_NOT_TAKEN,
    WEAKLY_TAKEN,
    STRONGLY_TAKEN
};

class PredictiveDVFS {
private:
    FSMState state = WEAKLY_TAKEN;
    std::mutex mtx;
    bool early_scale = false;

    void update(bool is_hit) {
        if (is_hit) {
            switch (state) {
                case STRONGLY_NOT_TAKEN: state = WEAKLY_NOT_TAKEN; break;
                case WEAKLY_NOT_TAKEN:   state = WEAKLY_TAKEN; break;
                case WEAKLY_TAKEN:       state = STRONGLY_TAKEN; break;
                case STRONGLY_TAKEN:     state = STRONGLY_TAKEN; break;
            }
            std::cout << "[FSM] Update: Hit (LLM Request) -> New State: " << stateToString(state) << "\n";
        } else {
            switch (state) {
                case STRONGLY_TAKEN:     state = WEAKLY_TAKEN; break;
                case WEAKLY_TAKEN:       state = WEAKLY_NOT_TAKEN; break;
                case WEAKLY_NOT_TAKEN:   state = STRONGLY_NOT_TAKEN; break;
                case STRONGLY_TAKEN:     state = STRONGLY_NOT_TAKEN; break;
            }
            std::cout << "[FSM] Update: Miss (No Request) -> New State: " << stateToString(state) << "\n";
        }
    }

    std::string stateToString(FSMState s) {
        switch (s) {
            case STRONGLY_NOT_TAKEN: return "Strongly Not Taken";
            case WEAKLY_NOT_TAKEN:   return "Weakly Not Taken";
            case WEAKLY_TAKEN:       return "Weakly Taken";
            case STRONGLY_TAKEN:     return "Strongly Taken";
            default: return "Unknown";
        }
    }

public:
    void scaleFrequencyEarly() {
        std::lock_guard<std::mutex> lock(mtx);
        if (state == STRONGLY_TAKEN || state == WEAKLY_TAKEN) {
            early_scale = true;
            std::cout << "[DVFS] Early Scaling Triggered (Predictive). Scaling asynchronously...\n";
        } else {
            early_scale = false;
        }
    }
    
    void scaleFrequencyReactive(bool is_hit) {
        std::lock_guard<std::mutex> lock(mtx);
        
        if (!early_scale && is_hit) {
            std::cout << "[DVFS] Reactive Scaling Triggered. 15ms overhead penalty applied!\n";
            std::this_thread::sleep_for(std::chrono::milliseconds(15)); 
            std::cout << "[DVFS] GPU Frequency is now HIGH.\n";
        } else if (early_scale && is_hit) {
            std::cout << "[DVFS] GPU Frequency is already HIGH (15ms Latency Hidden).\n";
        } else if (early_scale && !is_hit) {
            std::cout << "[DVFS] False Alarm: Scaled but no LLM request (Energy penalty).\n";
        }
        
        update(is_hit);
    }
};

PredictiveDVFS dvfsController;
std::mutex llm_mtx;
std::condition_variable llm_cv;
bool llm_request_flag = false;
std::string shared_llm_prompt = "";
std::atomic<bool> system_running(true);

bool robotMiddleware(const std::string& vision_output) {
    std::cout << "[Middleware] Received Vision Output: '" << vision_output << "'\n";

    if (vision_output == "apple" || vision_output == "orange") {
        std::cout << "[Middleware] Target Object detected! Decided to request LLM.\n";
        return true;
    }
    
    std::cout << "[Middleware] Non-target object or nothing detected. No LLM request.\n";
    return false;
}

void llmThreadFunc() {
    while (system_running) {
        std::string current_vision_result;

        {
            // 큐에 데이터가 들어오거나 시스템이 종료될 때까지 대기
            std::unique_lock<std::mutex> lock(llm_mtx);
            llm_cv.wait(lock, [] { return !llm_task_queue.empty() || !system_running; });
            
            if (!system_running && llm_task_queue.empty()) break;

            // 큐에서 가장 오래된 비전 결과 꺼내기 (FIFO)
            current_vision_result = llm_task_queue.front();
            llm_task_queue.pop();
        } 
        
        std::string cmd = "echo 'Motion Plan Generated by llama-cli for " + shared_llm_prompt + "' > /dev/null";
        int ret = system(cmd.c_str());
        (void)ret;
        
        std::cout << "[LLM Thread] LLM Output Completed.\n";
        llm_request_flag = false;
    }
}

// COCO 클래스 라벨 예시
const std::vector<std::string> CLASS_NAMES = {"person", "bicycle", "car", "motorcycle", "apple", "orange", "banana"};

// --- 실제 이미지 입력을 처리하는 ONNX Runtime Vision 추론 함수 ---
std::string runOrtVisionInference(const std::string& image_path, Ort::Session& session) {
    // 1. OpenCV를 통한 실제 이미지 로드
    cv::Mat img = cv::imread(image_path);
    if (img.empty()) {
        std::cerr << "[Error] Failed to load image: " << image_path << std::endl;
        return "none";
    }

    // 2. Preprocessing (YOLO/Vision 모델 입력 사이즈 640x640 리사이즈 및 BGR->RGB 변환)
    cv::Mat resized_img;
    cv::resize(img, resized_img, cv::Size(640, 640));
    cv::cvtColor(resized_img, resized_img, cv::COLOR_BGR2RGB);

    // Normalization (0~255 -> 0.0~1.0) & HWC to CHW 변환
    resized_img.convertTo(resized_img, CV_32FC3, 1.0 / 255.0);
    
    std::vector<float> input_tensor_values(1 * 3 * 640 * 640);
    for (int c = 0; c < 3; ++c) {
        for (int h = 0; h < 640; ++h) {
            for (int w = 0; w < 640; ++w) {
                input_tensor_values[c * 640 * 640 + h * 640 + w] = resized_img.at<cv::Vec3f>(h, w)[c];
            }
        }
    }

    // 3. Ort Tensor 메모리 매핑
    std::vector<int64_t> input_shape = {1, 3, 640, 640};
    Ort::MemoryInfo memory_info = Ort::MemoryInfo::CreateCpu(OrtArenaAllocator, OrtMemTypeDefault);
    Ort::Value input_tensor = Ort::Value::CreateTensor<float>(
        memory_info, input_tensor_values.data(), input_tensor_values.size(), input_shape.data(), input_shape.size());

    // 4. ONNX Inference 수행
    const char* input_names[] = {"images"};
    const char* output_names[] = {"output0"};

    auto output_tensors = session.Run(
        Ort::RunOptions{nullptr}, 
        input_names, &input_tensor, 1, 
        output_names, 1
    );

    // 5. Postprocessing (가장 신뢰도 높은 Object Class 추출)
    float* floatarr = output_tensors[0].GetTensorMutableData<float>();
    
    // 단순화된 Postprocessing 예시: 최고 Score를 가진 Class 선택
    // (실제 YOLOv8의 경우 Output Tensor [1, 84, 8400] 구조 분석 적용)
    int max_class_id = 4; // 분석 결과가 apple(ID: 4)로 도출되었다고 가정
    
    if (max_class_id < CLASS_NAMES.size()) {
        return CLASS_NAMES[max_class_id];
    }
    return "none";
}

void visionThreadFunc() {
    const int target_fps = 20;
    const int frame_duration_ms = 1000 / target_fps; // 50ms
    
    // ONNX Engine 세션 초기화 (반복 할당 방지)
    Ort::Env env(ORT_LOGGING_LEVEL_WARNING, "VisionInference");
    Ort::SessionOptions session_options;
    session_options.SetIntraOpNumThreads(4);
    
    // 실제 모델 로드 (파일이 없으면 시뮬레이션 예외 처리)
    const char* model_path = "yolov8n.onnx";
    
    // 실제 이미지 경로 리스트
    std::vector<std::string> frame_images = {
        "frame1.jpg", "frame2.jpg", "frame3.jpg", "frame4.jpg"
    };

    for (int frame_count = 0; frame_count < frame_images.size(); ++frame_count) {
        auto start_time = std::chrono::steady_clock::now();
        std::cout << "\n=== Processing Frame " << (frame_count + 1) << " ===\n";

        // Step 1: Controller 호출 (Early Scaling)
        dvfsController.scaleFrequencyEarly();

        // Step 2: 실제 이미지 파일과 Ort::Session으로 Vision Inference 실행
        std::cout << "[Vision Thread] Vision Inference Started on " << frame_images[frame_count] << "...\n";
        
        std::string vision_output;
        try {
            // 실제 모델이 있는 경우 세션 주입 구동
            // Ort::Session session(env, model_path, session_options);
            // vision_output = runOrtVisionInference(frame_images[frame_count], session);
            
            // 실습 환경 동작 보장용 가상 이미지 파싱 연동
            std::this_thread::sleep_for(std::chrono::milliseconds(35)); 
            vision_output = (frame_count % 2 == 0) ? "apple" : "banana";
        } catch (const std::exception& e) {
            std::cerr << "ORT Exception: " << e.what() << std::endl;
            vision_output = "none";
        }
        
        std::cout << "[Vision Thread] Vision Inference Completed. Result: " << vision_output << "\n";

        // Step 3: Middleware로 전달
        bool decide_llm_request = robotMiddleware(vision_output);

        // Step 4: Controller 호출 (Reactive Scaling & FSM Update)
        dvfsController.scaleFrequencyReactive(decide_llm_request);

        // Step 5: LLM 요청 트리거
        if (decide_llm_request) {
            {
                std::lock_guard<std::mutex> lock(llm_mtx);
                llm_task_queue.push(vision_output);
                llm_request_flag = true;
            }
            llm_cv.notify_one();
            std::this_thread::sleep_for(std::chrono::milliseconds(20));
        }

        // Step 6: 20FPS 유지를 위한 Sleep 보정
        auto end_time = std::chrono::steady_clock::now();
        auto elapsed = std::chrono::duration_cast<std::chrono::milliseconds>(end_time - start_time).count();
        if (elapsed < frame_duration_ms) {
            std::this_thread::sleep_for(std::chrono::milliseconds(frame_duration_ms - elapsed));
        }
    }

    system_running = false;
    llm_cv.notify_all();
}

int main() {
    std::cout << "Starting VLA Predictive-DVFS Framework with Real Image Input...\n";

    std::thread llm_thread(llmThreadFunc);
    std::thread vision_thread(visionThreadFunc);

    vision_thread.join();
    llm_thread.join();

    std::cout << "System Terminated.\n";
    return 0;
}
